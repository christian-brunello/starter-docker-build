#!/usr/bin/env bash
# Export enabled host systemd units (starter-core + st-*) into overlay boot-services.conf.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
DEST="${ROOT}/overlay/etc/starter/boot-services.conf"
UNIT_DIRS=(/lib/systemd/system /etc/systemd/system)
WANTS_DIR=/etc/systemd/system/multi-user.target.wants

collect_enabled_units() {
    local f base
    # Prefer wants symlinks (authoritative for "enabled at boot")
    if [[ -d "${WANTS_DIR}" ]]; then
        for f in "${WANTS_DIR}"/starter-core.service "${WANTS_DIR}"/st-*.service; do
            [[ -e "${f}" ]] || continue
            base="$(basename "${f}")"
            # Resolve to a real unit file
            for d in "${UNIT_DIRS[@]}"; do
                if [[ -f "${d}/${base}" ]]; then
                    printf '%s\n' "${d}/${base}"
                    break
                fi
            done
        done
    fi
    # Fallback: unit-files marked enabled
    if command -v systemctl >/dev/null 2>&1; then
        systemctl list-unit-files 'starter-core.service' 'st-*.service' --state=enabled --no-legend --no-pager 2>/dev/null \
        | awk '{print $1}' \
        | while read -r base; do
            [[ -n "${base}" ]] || continue
            for d in "${UNIT_DIRS[@]}"; do
                if [[ -f "${d}/${base}" ]]; then
                    printf '%s\n' "${d}/${base}"
                    break
                fi
            done
        done
    fi
}

parse_unit() {
    local unit="$1"
    local name user exec_line
    name="$(basename "${unit}" .service)"
    user="$(grep -E '^User=' "${unit}" | head -1 | cut -d= -f2- || true)"
    user="${user:-root}"
    exec_line="$(grep -E '^ExecStart=' "${unit}" | head -1 | cut -d= -f2- || true)"
    if [[ -z "${exec_line}" ]]; then
        echo "warning: no ExecStart in ${unit}" >&2
        return 1
    fi
    # Strip absolute path prefixes so PATH finds /usr/local/bin inside the image
    exec_line="${exec_line//\/usr\/local\/bin\//}"
    printf '%s|%s|%s\n' "${name}" "${user}" "${exec_line}"
}

classify() {
    # Order: core → adapters → services
    case "$1" in
        starter-core) echo 0 ;;
        *-adapter|st-ariston*|st-parameters-adapter) echo 1 ;;
        *) echo 2 ;;
    esac
}

tmpdir="$(mktemp -d)"
trap 'rm -rf "${tmpdir}"' EXIT

: > "${tmpdir}/raw"
while read -r unit; do
    [[ -n "${unit}" ]] || continue
    parse_unit "${unit}" >> "${tmpdir}/raw" || true
done < <(collect_enabled_units | sort -u || true)

: > "${tmpdir}/sorted"
if [[ -s "${tmpdir}/raw" ]]; then
    while IFS='|' read -r name user cmd; do
        [[ -n "${name}" ]] || continue
        printf '%s|%s|%s|%s\n' "$(classify "${name}")" "${name}" "${user}" "${cmd}"
    done < "${tmpdir}/raw" | sort -t'|' -k1,1n -k2,2 | while IFS='|' read -r _ord name user cmd; do
        printf '%s|%s|%s\n' "${name}" "${user}" "${cmd}"
    done > "${tmpdir}/sorted" || true
fi

# Deduplicate by name (first wins)
: > "${tmpdir}/final"
declare -A seen=()
while IFS='|' read -r name user cmd; do
    [[ -n "${name}" ]] || continue
    if [[ -n "${seen[$name]:-}" ]]; then
        continue
    fi
    seen[$name]=1
    printf '%s|%s|%s\n' "${name}" "${user}" "${cmd}" >> "${tmpdir}/final"
done < "${tmpdir}/sorted"

mkdir -p "$(dirname "${DEST}")"
{
    echo "# Boot services for the STARTER Docker container (supervisord)."
    echo "# Generated by scripts/sync-boot-services.sh — format: name|user|command..."
    echo "# Seeded into /usr/local/etc/starter/boot-services.conf (etc volume)."
    echo "#"
    cat "${tmpdir}/final"
} > "${DEST}"

count="$(grep -cE '^[^#]' "${DEST}" || true)"
echo "Wrote ${DEST} (${count} programs)"
sed -n '4,40p' "${DEST}"
echo
echo "Rebuild the image to refresh defaults: ./build.sh"
echo "Existing boot-services.conf on the etc volume is never overwritten at runtime."
