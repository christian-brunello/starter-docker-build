#!/usr/bin/env bash
# Service mode: wait for MySQL settle, then run supervisord with programs from
# boot-services.conf (core + adapters + services). Falls back to starter-core only.
set -euo pipefail

BOOT_CONF="${STARTER_BOOT_SERVICES:-/usr/local/etc/starter/boot-services.conf}"
RULES="${STARTER_RULES_FILE:-/usr/local/etc/starter/rules.conf}"
MATCH="${STARTER_SERVICE_MATCH:-}"
SUPER_DIR=/run/starter
SUPER_CONF="${SUPER_DIR}/supervisord.conf"
LOG_DIR=/var/log/supervisor
SETTLE_SECS="${STARTER_BOOT_SETTLE_SECS:-15}"

start_core_only() {
    if [[ ! -f "${RULES}" ]]; then
        echo "error: rules file not found: ${RULES}" >&2
        exit 1
    fi
    local -a cmd=(starter-core -R "${RULES}")
    if [[ -n "${MATCH}" ]]; then
        cmd+=(-m "${MATCH}")
    fi
    echo "Starting: ${cmd[*]} (user=starter)"
    exec runuser -u starter -- env \
        HOME=/home/starter \
        XDG_DATA_DIRS=/usr/local/share:/usr/share \
        "${cmd[@]}"
}

write_supervisord_conf() {
    local manifest="$1"
    install -d -m 755 "${SUPER_DIR}" "${LOG_DIR}"

    {
        cat <<EOF
; Generated by container-main.sh — do not edit
[supervisord]
nodaemon=true
user=root
logfile=${LOG_DIR}/supervisord.log
pidfile=${SUPER_DIR}/supervisord.pid
childlogdir=${LOG_DIR}
silent=false

[unix_http_server]
file=${SUPER_DIR}/supervisor.sock

[rpcinterface:supervisor]
supervisor.rpcinterface_factory = supervisor.rpcinterface:make_main_rpcinterface

[supervisorctl]
serverurl=unix://${SUPER_DIR}/supervisor.sock

EOF

        local priority=100
        local name user cmd prog_user env_line
        while IFS='|' read -r name user cmd || [[ -n "${name:-}" ]]; do
            [[ -z "${name:-}" ]] && continue
            [[ "${name}" =~ ^# ]] && continue
            [[ -z "${cmd:-}" ]] && continue

            # Optional -m match for starter-core
            if [[ "${name}" == "starter-core" && -n "${MATCH}" ]]; then
                case " ${cmd} " in
                    *" -m "*|*" -m"*) ;;
                    *) cmd="${cmd} -m ${MATCH}" ;;
                esac
            fi

            if [[ "${user}" == "root" ]]; then
                prog_user="root"
                env_line='environment=HOME="/root",XDG_DATA_DIRS="/usr/local/share:/usr/share"'
            else
                prog_user="starter"
                env_line='environment=HOME="/home/starter",XDG_DATA_DIRS="/usr/local/share:/usr/share"'
            fi
            # PulseAudio for starter-explain (paplay) when host socket is mounted
            if [[ -n "${PULSE_SERVER:-}" ]]; then
                env_line+=",PULSE_SERVER=\"${PULSE_SERVER}\""
            fi
            if [[ -n "${XDG_RUNTIME_DIR:-}" ]]; then
                env_line+=",XDG_RUNTIME_DIR=\"${XDG_RUNTIME_DIR}\""
            fi
            if [[ -n "${PULSE_COOKIE:-}" ]]; then
                env_line+=",PULSE_COOKIE=\"${PULSE_COOKIE}\""
            fi

            # supervisord program names: alphanumeric, underscore, hyphen
            local prog="${name//[^A-Za-z0-9_-]/_}"

            cat <<EOF
[program:${prog}]
command=${cmd}
user=${prog_user}
${env_line}
directory=/home/starter
autostart=true
autorestart=true
startsecs=2
startretries=20
stopwaitsecs=30
stdout_logfile=/dev/stdout
stdout_logfile_maxbytes=0
stderr_logfile=/dev/stderr
stderr_logfile_maxbytes=0
priority=${priority}

EOF
            priority=$((priority + 10))
        done < "${manifest}"
    } > "${SUPER_CONF}"
}

# Mirror host starter-core ExecStartPre sleep so adapters/services see a ready DB.
echo "Waiting ${SETTLE_SECS}s after MySQL init (STARTER_BOOT_SETTLE_SECS)..."
sleep "${SETTLE_SECS}"

if [[ ! -f "${BOOT_CONF}" ]]; then
    echo "warning: ${BOOT_CONF} missing — starting starter-core only" >&2
    start_core_only
fi

# Count non-comment, non-empty lines
prog_count="$(grep -cE '^[^#[:space:]]' "${BOOT_CONF}" 2>/dev/null || true)"
if [[ "${prog_count}" -lt 1 ]]; then
    echo "warning: ${BOOT_CONF} empty — starting starter-core only" >&2
    start_core_only
fi

if ! command -v supervisord >/dev/null 2>&1; then
    echo "warning: supervisord not installed — starting starter-core only" >&2
    start_core_only
fi

write_supervisord_conf "${BOOT_CONF}"
echo "Starting supervisord with ${prog_count} program(s) from ${BOOT_CONF}"
exec supervisord -n -c "${SUPER_CONF}"
